(* Build-time tool. Usage: embed_headers file1.h file2.h ...

   Prints an OCaml module on stdout that holds the contents of those files, so
   that the compiler carries its own standard headers inside its executable and
   needs no installation step. The generated code looks like

     let headers = [ ("stdio.h", {hdr|...file contents...|hdr}); ... ]
     let find name = List.assoc_opt name headers

   {hdr|...|hdr} is an OCaml "quoted string": it holds any text verbatim, with
   no escaping, as long as it doesn't contain the closing marker. *)

let read path = In_channel.with_open_bin path In_channel.input_all

let () =
  print_endline "(* Generated by tools/embed_headers.ml: do not edit. *)";
  print_endline "let headers = [";
  Array.iteri
    (fun i path ->
      if i > 0 then
        Printf.printf "  (%S, {hdr|%s|hdr});\n" (Filename.basename path) (read path))
    Sys.argv;
  print_endline "]";
  print_endline "let find name = List.assoc_opt name headers"
